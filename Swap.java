public class Swap {
    public static void main(String[] args) {
        int a=68;
        int b = 69;
        
        // Swapping logic using a temporary variable
        int c=a;
        a=b;
        b=c;

        System.out.println("a = " + a);
        System.out.println("b = " + b);

    }
    
}
