import java.util.Scanner;

public class MaximumAndMinimumOfThreeNumbers {
    //  Write a program to find the maximum and minimum of three numbers using nested if taken from the user. 
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        
        System.out.print("Enter first number: ");
        int num1 = sc.nextInt();
        System.out.print("Enter second number: ");
        int num2 = sc.nextInt();
        System.out.print("Enter third number: ");
        int num3 = sc.nextInt();

        int max, min;

        // Finding maximum
        if (num1 >= num2 && num1 >= num3) {
            max = num1;
        } else if (num2 >= num1 && num2 >= num3) {
            max = num2;
        } else {
            max = num3;
        }

        // Finding minimum
        if (num1 <= num2 && num1 <= num3) {
            min = num1;
        } else if (num2 <= num1 && num2 <= num3) {
            min = num2;
        } else {
            min = num3;
        }

        System.out.println("Maximum of three numbers: " + max);
        System.out.println("Minimum of three numbers: " + min);

        sc.close();
    }
}
